#!/usr/bin/env python3
"""Maintain klippain_mmu_v4_fix.cfg: copies of the Klippain MMU macros that still read Happy Hare v3's [mmu] config section.

  tools/mmu_v4_fix.py gen   [--src PATH] [--out PATH]    regenerate the override file from the installed Klippain
  tools/mmu_v4_fix.py check [--src PATH] [--fix PATH]    verify the override is still valid after a Klippain/Happy Hare update

Why a guard: the override shadows upstream. If Klippain later changes those macros (or fixes them), a stale copy would silently
keep running the OLD logic. `check` exits 1 when the copies no longer match what the current Klippain would produce, and prints
what to do. It is read-only. Run by tools/validate.sh and by the update-guard git hooks (tools/install-update-guard.sh).
"""
import argparse
import hashlib
import os
import re
import subprocess
import sys

HOME = os.path.expanduser("~")
CFG = os.environ.get("CFG", os.path.join(HOME, "printer_data", "config"))
DEFAULT_SRC = os.path.join(CFG, "macros", "hardware_functions", "mmu.cfg")
DEFAULT_FIX = os.path.join(CFG, "klippain_mmu_v4_fix.cfg")
UNIT = 'printer.configfile.config["mmu_unit_parameters unit0"]'
MARK = "# BASE-SHA256:"

HEADER = """# Klippain's MMU macros (macros/hardware_functions/mmu.cfg) were written for Happy Hare v3, which had an [mmu] config section.
# Happy Hare v4 has [mmu_parameters] / [mmu_unit_parameters unit0] instead, so printer.configfile.config.mmu.* raised
# "'dict object' has no attribute 'mmu'" and aborted START_PRINT. These are copies of ONLY the affected macros with the
# lookups pointed at [mmu_unit_parameters unit0]. Included last from printer.cfg so they override the Klippain versions.
# GENERATED by tools/mmu_v4_fix.py gen. Do not hand-edit. After a Klippain or Happy Hare update run
# `tools/mmu_v4_fix.py check` (tools/validate.sh does); it says whether to regenerate or to delete this file.
"""


def read(path):
    with open(path, encoding="utf-8") as fh:
        return fh.read().replace("\r\n", "\n")


def affected(src):
    """Return [(name, text)] for macros in src that read the v3 [mmu] section."""
    parts = re.split(r"(?m)^(?=\[gcode_macro )", src)
    out = []
    for p in parts:
        m = re.match(r"\[gcode_macro (\S+)\]", p)
        if m and "config.mmu" in p:
            out.append((m.group(1), p))
    return out


def rewrite(text):
    q = re.sub(r"printer\.configfile\.config\.mmu\.sync_to_extruder\s*==\s*(\d)",
               lambda m: UNIT + ".sync_to_extruder|default(0)|int == " + m.group(1), text)
    q = q.replace("printer.configfile.config.mmu.selector_touch_enable",
                  UNIT + ".selector_touch_enable|default('n/a')")
    if "config.mmu" in q:
        raise SystemExit("unhandled [mmu] reference, extend rewrite():\n" + q[:200])
    return q.rstrip() + "\n"


def build(src):
    macros = affected(src)
    body = "\n".join(rewrite(t) for _, t in macros)
    sha = hashlib.sha256(src.encode()).hexdigest()
    return HEADER + "%s %s\n\n" % (MARK, sha) + body, [n for n, _ in macros], sha


def klippain_rev(src_path):
    try:
        d = os.path.dirname(os.path.realpath(src_path))
        return subprocess.check_output(["git", "-C", d, "rev-parse", "--short", "HEAD"], stderr=subprocess.DEVNULL).decode().strip()
    except Exception:
        return "unknown"


def cmd_gen(a):
    text, names, sha = build(read(a.src))
    with open(a.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote %s: %d macros (%s) from Klippain %s, base sha %s" % (a.out, len(names), ", ".join(names), klippain_rev(a.src), sha[:12]))
    return 0


def body_of(text):
    """The part after the BASE-SHA256 line."""
    i = text.find(MARK)
    return text[text.find("\n", i) + 1:] if i >= 0 else text


def missing_callees(fix_text, mr="http://localhost:7125"):
    """Commands (macros) our override invokes that the running Klipper does not define. Skipped when Moonraker is unreachable."""
    import json
    import urllib.request
    try:
        with urllib.request.urlopen(mr + "/printer/gcode/help", timeout=5) as r:
            known = set(json.load(r)["result"])
    except Exception:
        return []
    own = set(re.findall(r"(?m)^\[gcode_macro (\S+)\]", fix_text))
    called = set()
    for line in body_of(fix_text).splitlines():
        s = line.strip()
        if not s or s.startswith(("#", "{%", "{", "}")):
            continue
        tok = s.split()[0]
        if re.fullmatch(r"_?[A-Z][A-Z0-9_]{2,}", tok) and tok not in ("RESPOND", "PREFIX"):
            called.add(tok)
    # commands Klipper provides without a help line, or that are only ever defined at runtime
    builtin_ok = {"SET_GCODE_VARIABLE", "SAVE_GCODE_STATE", "RESTORE_GCODE_STATE"}
    return sorted(c for c in called if c not in known and c not in own and c not in builtin_ok)


def cmd_check(a):
    if not os.path.exists(a.fix):
        print("[WARN] no %s (nothing to check)" % a.fix)
        return 0
    if not os.path.exists(a.src):
        print("[FAIL] Klippain MMU macros not found at %s" % a.src)
        return 1
    src = read(a.src)
    have = read(a.fix)
    m = re.search(re.escape(MARK) + r" (\w+)", have)
    base = m.group(1) if m else ""
    now = hashlib.sha256(src.encode()).hexdigest()
    want, names, _ = build(src)
    if not names:
        print("[WARN] upstream Klippain no longer reads the v3 [mmu] section: %s is probably obsolete.\n"
              "       Remove its [include klippain_mmu_v4_fix.cfg] line from printer.cfg and delete the file, then run a dry START_PRINT." % os.path.basename(a.fix))
        return 0
    have_names = re.findall(r"(?m)^\[gcode_macro (\S+)\]", have)
    if sorted(have_names) != sorted(names):
        print("[FAIL] override macros %s != macros upstream still needing a patch %s.\n"
              "       Regenerate: tools/mmu_v4_fix.py gen" % (sorted(have_names), sorted(names)))
        return 1
    if body_of(have).strip() != body_of(want).strip():
        import difflib
        diff = "".join(difflib.unified_diff(body_of(have).splitlines(True), body_of(want).splitlines(True), "committed override", "regenerated from current Klippain", n=2))
        print("[FAIL] Klippain/Happy Hare changed the macros we override (Klippain %s). The old copy would shadow the new logic.\n"
              "       Review the diff, then regenerate: tools/mmu_v4_fix.py gen, commit, restart Klipper, dry-run a START_PRINT.\n%s" % (klippain_rev(a.src), diff[:3000]))
        return 1
    missing = missing_callees(have)
    if missing:
        print("[FAIL] the override calls commands the printer no longer defines (renamed/removed by an update?): %s.\n"
              "       Review Klippain's current macros/hardware_functions/mmu.cfg, then regenerate: tools/mmu_v4_fix.py gen" % ", ".join(missing))
        return 1
    if base != now:
        print("[OK]   overrides still match Klippain %s (upstream file changed elsewhere; run `tools/mmu_v4_fix.py gen` to refresh the base hash)" % klippain_rev(a.src))
    else:
        print("[OK]   overrides match Klippain %s (%d macros: %s)" % (klippain_rev(a.src), len(names), ", ".join(names)))
    return 0


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    g = sub.add_parser("gen"); g.add_argument("--src", default=DEFAULT_SRC); g.add_argument("--out", default=DEFAULT_FIX)
    c = sub.add_parser("check"); c.add_argument("--src", default=DEFAULT_SRC); c.add_argument("--fix", default=DEFAULT_FIX)
    a = ap.parse_args()
    return cmd_gen(a) if a.cmd == "gen" else cmd_check(a)


if __name__ == "__main__":
    sys.exit(main())
